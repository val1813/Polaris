"""
Polaris Structural Quality Metrics
Domain-agnostic. Works on ANY run. No ground truth needed.
Usage: python benchmarks/metrics.py <run_directory>
"""

import json, sys, re
from pathlib import Path


def check_gate_minus1(run_dir: Path) -> dict:
    """GATE -1: Was core contradiction validated with three Yes answers?"""
    phase_list = run_dir / "project" / "Phase清单.md"
    if not phase_list.exists():
        return {"pass": False, "reason": "Phase清单.md not found"}

    content = phase_list.read_text(encoding='utf-8')
    q1 = "Q-1.1" in content or "Q1.1" in content
    q2 = "Q-1.2" in content or "Q1.2" in content
    q3 = "Q-1.3" in content or "Q1.3" in content
    all_yes = "YES" in content or "通过" in content

    return {"pass": q1 and q2 and q3 and all_yes, "checks": {"Q1.1": q1, "Q1.2": q2, "Q1.3": q3}}


def check_min_rounds(run_dir: Path) -> dict:
    """Minimum 3 rounds enforced?"""
    # Count round directories
    rounds_a = list((run_dir / "current" / "A").glob("round*"))
    rounds_b = list((run_dir / "current" / "B").glob("round*"))
    n_rounds = max(len(rounds_a), len(rounds_b))

    return {
        "pass": n_rounds >= 3,
        "rounds_found": n_rounds,
        "min_required": 3
    }


def check_inspector_independence(run_dir: Path) -> dict:
    """Were INSPECTOR reports generated by independent Agents?"""
    inspector_files = list((run_dir / "synthesis").glob("inspector_*"))
    if not inspector_files:
        return {"pass": False, "reason": "No inspector files found"}

    # Check: do inspector files reference Agent tool usage?
    independent = False
    for f in inspector_files:
        content = f.read_text(encoding='utf-8')
        if "Agent" in content or "INSPECTOR" in content:
            independent = True
            break

    return {
        "pass": independent,
        "inspector_count": len(inspector_files),
        "note": "Check that INSPECTOR was launched via Agent tool, not written by PI"
    }


def check_ab_isolation(run_dir: Path) -> dict:
    """A and B used different frameworks?"""
    phase_list = run_dir / "project" / "Phase清单.md"
    if not phase_list.exists():
        return {"pass": False}

    content = phase_list.read_text(encoding='utf-8')
    frameworks_different = "不同" in content or "≠" in content

    return {
        "pass": frameworks_different,
        "note": "Check Phase清单 AB探索 section for framework comparison"
    }


def check_reviewer_triggered(run_dir: Path) -> dict:
    """REVIEWER triggered at least once (round 3+)?"""
    phase_list = run_dir / "project" / "Phase清单.md"
    if not phase_list.exists():
        return {"pass": False}

    content = phase_list.read_text(encoding='utf-8')
    reviewer_triggered = "REVIEWER" in content

    reviewer_files = list((run_dir / "synthesis").glob("reviewer_*"))
    return {
        "pass": reviewer_triggered or len(reviewer_files) > 0,
        "reviewer_files": len(reviewer_files)
    }


def check_prior_art_gate(run_dir: Path) -> dict:
    """R1 prior art interception performed?"""
    phase_list = run_dir / "project" / "Phase清单.md"
    if not phase_list.exists():
        return {"pass": False}

    content = phase_list.read_text(encoding='utf-8')
    prior_art_checked = "先发拦截" in content or "R1先发" in content

    return {"pass": prior_art_checked, "note": "Check Phase清单 for R1 prior art gate"}


def check_aha_activity(run_dir: Path) -> dict:
    """Any AHA triggered during the run?"""
    aha_files = list((run_dir / "synthesis").glob("aha_*"))
    phase_list = run_dir / "project" / "Phase清单.md"
    content = ""
    if phase_list.exists():
        content = phase_list.read_text(encoding='utf-8')

    aha_triggered = "AHA" in content or len(aha_files) > 0

    return {
        "pass": True,  # Not having AHA is not a failure — it's a finding
        "aha_triggered": aha_triggered,
        "aha_files": len(aha_files),
        "note": "AHA absence is not a failure. This metric is informational."
    }


def score_run(run_dir: str) -> dict:
    """Score a run on structural quality — domain agnostic."""
    path = Path(run_dir)
    if not path.exists():
        return {"error": f"Directory not found: {run_dir}"}

    checks = {
        "GATE-1_core_contradiction": check_gate_minus1(path),
        "min_3_rounds": check_min_rounds(path),
        "inspector_independence": check_inspector_independence(path),
        "ab_isolation": check_ab_isolation(path),
        "reviewer_triggered": check_reviewer_triggered(path),
        "prior_art_interception": check_prior_art_gate(path),
        "aha_activity": check_aha_activity(path)
    }

    passed = sum(1 for c in checks.values() if c.get("pass", False))
    total = len(checks)
    score = round(passed / total * 100)

    return {
        "run": run_dir,
        "score": f"{passed}/{total} ({score}%)",
        "checks": checks,
        "verdict": "PASS" if score >= 70 else "FAIL"
    }


if __name__ == "__main__":
    if len(sys.argv) < 2:
        print("Usage: python benchmarks/metrics.py <run_directory>")
        print("  Scores ANY Polaris run on structural quality — no ground truth needed.")
        sys.exit(1)

    result = score_run(sys.argv[1])
    print(json.dumps(result, indent=2, ensure_ascii=True))
